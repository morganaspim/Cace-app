from __future__ import annotations
from abc import ABC, abstractmethod
from dataclasses import dataclass
from typing import Any, Mapping
from .types import ModuleMetadata, PortSpec, ParameterSpec, ProofStatus
from .verification import VerificationRecord
from .device import DeviceSelection

class ValidationError(ValueError):
    pass

@dataclass
class ExecutionContext:
    run_id: str
    seed: int = 0
    device: DeviceSelection | None = None

class Module(ABC):
    metadata: ModuleMetadata
    inputs: tuple[PortSpec, ...] = ()
    outputs: tuple[PortSpec, ...] = ()
    parameters: tuple[ParameterSpec, ...] = ()
    proof_status: ProofStatus = ProofStatus()
    supports_gpu: bool = False

    def validate(self, inputs: Mapping[str, Any], params: Mapping[str, Any]) -> None:
        missing = [p.name for p in self.inputs if p.required and p.name not in inputs]
        if missing:
            raise ValidationError(f"{self.metadata.module_id}: missing inputs {missing}")
        known = {p.name for p in self.parameters}
        unknown = set(params) - known
        if unknown:
            raise ValidationError(f"{self.metadata.module_id}: unknown parameters {sorted(unknown)}")

    def resolved_params(self, params: Mapping[str, Any]) -> dict[str, Any]:
        out = {p.name: p.default for p in self.parameters}
        out.update(params)
        return out

    @abstractmethod
    def execute(self, inputs: Mapping[str, Any], params: Mapping[str, Any], ctx: ExecutionContext) -> Mapping[str, Any]:
        raise NotImplementedError

    def verify(self, inputs: Mapping[str, Any], params: Mapping[str, Any], outputs: Mapping[str, Any], ctx: ExecutionContext) -> list[VerificationRecord]:
        """Return evidence generated by verifiers that actually ran. Empty is valid."""
        return []
