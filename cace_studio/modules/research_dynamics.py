from __future__ import annotations

import math
from typing import Mapping, Any

import numpy as np

from cace_studio.core.module import Module, ExecutionContext, ValidationError
from cace_studio.core.types import (
    EvidenceKind,
    Maturity,
    ModuleMetadata,
    ParameterSpec,
    PortSpec,
    ProofStatus,
)
from cace_studio.core.verification import VerificationRecord, VerificationState


def plane_rotation_matrix(dimensions: int, axis_a: int, axis_b: int, angle: float) -> np.ndarray:
    """Return the canonical orientation-preserving rotation in one R^n coordinate plane.

    This is a real orthogonal transformation, not an assertion that Euler's complex
    identity generalizes as scalar multiplication in arbitrary dimensions.  In the
    selected two-plane it is exactly the usual 2D rotation; all orthogonal
    coordinates are fixed.
    """
    if dimensions < 2:
        raise ValueError("dimensions must be >= 2")
    if not (0 <= axis_a < dimensions and 0 <= axis_b < dimensions):
        raise ValueError("rotation axes must be valid coordinate indices")
    if axis_a == axis_b:
        raise ValueError("rotation axes must be distinct")
    if not math.isfinite(angle):
        raise ValueError("rotation angle must be finite")

    matrix = np.eye(dimensions, dtype=float)
    c = math.cos(angle)
    s = math.sin(angle)
    matrix[axis_a, axis_a] = c
    matrix[axis_a, axis_b] = -s
    matrix[axis_b, axis_a] = s
    matrix[axis_b, axis_b] = c
    return matrix


class GrowthRotationRandomWalk(Module):
    """Euler-inspired, but rigorously real-valued, stochastic dynamics in R^n.

    The recurrence is

        x[k+1] = exp(g*dt) R_ab(theta) x[k] + sigma sqrt(dt) xi[k]

    where R_ab(theta) is an orthogonal plane rotation and xi[k] is an isotropic
    unit direction sampled deterministically from the experiment seed.  This is a
    research model for exploring coupled growth, rotation, and random forcing; it
    does not constitute evidence for a physical law or a mathematical theorem.
    """

    metadata = ModuleMetadata(
        "research.growth_rotation_walk",
        "Growth + Rotation Random Walk",
        "0.1.0",
        "Research Dynamics",
        "Deterministic-seed R^n stochastic dynamics with exponential growth and orthogonal plane rotation.",
        Maturity.EXPERIMENTAL,
        assumptions=(
            "State space is Euclidean R^n.",
            "Random forcing is generated by NumPy PCG64 through default_rng using the experiment seed.",
            "The Euler e^(i*pi)=-1 identity is motivational only; rotation is implemented as an explicit real orthogonal matrix.",
        ),
    )
    outputs = (
        PortSpec("trajectory", "array"),
        PortSpec("radii", "array"),
        PortSpec("rotation_matrix", "array"),
        PortSpec("growth_factor", "number"),
        PortSpec("orthogonality_defect", "number"),
        PortSpec("seed", "integer"),
    )
    parameters = (
        ParameterSpec("dimensions", "integer", 3, "State-space dimension, 2..64"),
        ParameterSpec("steps", "integer", 256, "Number of discrete updates, 1..100000"),
        ParameterSpec("dt", "number", 0.01, "Positive time increment", unit="s"),
        ParameterSpec("log_growth_rate", "number", 0.0, "Continuous exponential growth rate", unit="1/s"),
        ParameterSpec("rotation_angle", "number", math.pi / 32.0, "Rotation per step in the selected coordinate plane", unit="rad"),
        ParameterSpec("axis_a", "integer", 0, "First rotation-plane coordinate index"),
        ParameterSpec("axis_b", "integer", 1, "Second rotation-plane coordinate index"),
        ParameterSpec("noise_scale", "number", 1.0, "Random forcing scale"),
        ParameterSpec("initial_radius", "number", 1.0, "Initial norm on coordinate axis 0"),
    )
    proof_status = ProofStatus(
        evidence={EvidenceKind.EXPERIMENTAL, EvidenceKind.NUMERICAL},
        unit_tests=True,
        property_tests=True,
        documentation=True,
        limitations=[
            "Research/experimental model only; no physical-law claim is made.",
            "Numerical orthogonality checks are not formal proof evidence.",
            "Floating-point trajectories can overflow for extreme growth/step choices; such runs are rejected by verification.",
            "No complex-number or geometric-algebra semantics are inferred from the Euler-identity analogy.",
        ],
    )

    def validate(self, inputs: Mapping[str, Any], params: Mapping[str, Any]) -> None:
        super().validate(inputs, params)
        p = self.resolved_params(params)
        dimensions = int(p["dimensions"])
        steps = int(p["steps"])
        dt = float(p["dt"])
        growth = float(p["log_growth_rate"])
        angle = float(p["rotation_angle"])
        noise_scale = float(p["noise_scale"])
        initial_radius = float(p["initial_radius"])
        axis_a = int(p["axis_a"])
        axis_b = int(p["axis_b"])

        if not 2 <= dimensions <= 64:
            raise ValidationError("GrowthRotationRandomWalk requires 2 <= dimensions <= 64")
        if not 1 <= steps <= 100_000:
            raise ValidationError("GrowthRotationRandomWalk requires 1 <= steps <= 100000")
        if not math.isfinite(dt) or dt <= 0.0:
            raise ValidationError("GrowthRotationRandomWalk requires finite dt > 0")
        for name, value in (
            ("log_growth_rate", growth),
            ("rotation_angle", angle),
            ("noise_scale", noise_scale),
            ("initial_radius", initial_radius),
        ):
            if not math.isfinite(value):
                raise ValidationError(f"GrowthRotationRandomWalk requires finite {name}")
        if noise_scale < 0.0:
            raise ValidationError("GrowthRotationRandomWalk requires noise_scale >= 0")
        if initial_radius < 0.0:
            raise ValidationError("GrowthRotationRandomWalk requires initial_radius >= 0")
        if not (0 <= axis_a < dimensions and 0 <= axis_b < dimensions):
            raise ValidationError("rotation axes must be valid coordinate indices")
        if axis_a == axis_b:
            raise ValidationError("rotation axes must be distinct")

        exponent = growth * dt
        if exponent > math.log(np.finfo(float).max) or exponent < math.log(np.finfo(float).tiny):
            raise ValidationError("per-step exponential growth factor is outside finite binary64 range")

    def execute(self, inputs: Mapping[str, Any], params: Mapping[str, Any], ctx: ExecutionContext) -> Mapping[str, Any]:
        dimensions = int(params["dimensions"])
        steps = int(params["steps"])
        dt = float(params["dt"])
        growth_factor = math.exp(float(params["log_growth_rate"]) * dt)
        rotation = plane_rotation_matrix(
            dimensions,
            int(params["axis_a"]),
            int(params["axis_b"]),
            float(params["rotation_angle"]),
        )
        noise_scale = float(params["noise_scale"])

        trajectory = np.empty((steps + 1, dimensions), dtype=float)
        trajectory[0] = 0.0
        trajectory[0, 0] = float(params["initial_radius"])
        rng = np.random.default_rng(ctx.seed)
        noise_step = noise_scale * math.sqrt(dt)

        for index in range(steps):
            direction = rng.normal(size=dimensions)
            norm = float(np.linalg.norm(direction))
            if norm == 0.0:
                direction = np.zeros(dimensions, dtype=float)
                direction[0] = 1.0
            else:
                direction /= norm
            trajectory[index + 1] = growth_factor * (rotation @ trajectory[index]) + noise_step * direction

        radii = np.linalg.norm(trajectory, axis=1)
        orthogonality_defect = float(
            np.linalg.norm(rotation.T @ rotation - np.eye(dimensions), ord=np.inf)
        )
        return {
            "trajectory": trajectory,
            "radii": radii,
            "rotation_matrix": rotation,
            "growth_factor": growth_factor,
            "orthogonality_defect": orthogonality_defect,
            "seed": int(ctx.seed),
        }

    def verify(self, inputs, params, outputs, ctx):
        trajectory = np.asarray(outputs["trajectory"], dtype=float)
        rotation = np.asarray(outputs["rotation_matrix"], dtype=float)
        dimensions = int(params["dimensions"])
        steps = int(params["steps"])
        defect = float(np.linalg.norm(rotation.T @ rotation - np.eye(dimensions), ord=np.inf))
        finite = bool(np.all(np.isfinite(trajectory)) and math.isfinite(float(outputs["growth_factor"])))
        shape_ok = trajectory.shape == (steps + 1, dimensions)
        ortho_ok = defect <= 1e-12
        return [
            VerificationRecord(
                "growth-rotation-shape-finite",
                EvidenceKind.NUMERICAL,
                "trajectory has requested finite R^n shape",
                VerificationState.PASS if finite and shape_ok else VerificationState.FAIL,
                "host-side shape and finite-value checks",
                {
                    "shape": list(trajectory.shape),
                    "expected_shape": [steps + 1, dimensions],
                    "seed": int(ctx.seed),
                },
                notes=("Numerical verification only; no theorem is promoted.",),
            ),
            VerificationRecord(
                "growth-rotation-orthogonality",
                EvidenceKind.NUMERICAL,
                "selected-plane rotation is numerically orthogonal",
                VerificationState.PASS if ortho_ok else VerificationState.FAIL,
                "infinity norm of R^T R - I",
                {"orthogonality_defect": defect, "tolerance": 1e-12},
                notes=("Analytic construction is standard; this record is still only runtime numerical evidence.",),
            ),
        ]


def register_research_dynamics(registry) -> None:
    registry.register(GrowthRotationRandomWalk)
